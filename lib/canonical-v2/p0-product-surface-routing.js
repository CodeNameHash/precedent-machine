function routeGeneralCovenantCode(rawCode) {
  const code = typeof rawCode === 'string' ? rawCode.trim().toUpperCase() : '';
  if (!code) {
    return Object.freeze({
      code: null,
      owner_id: 'UNTYPED_GENERAL_COVENANT_REVIEW',
      route_state: 'REVIEW_REQUIRED',
    });
  }
  if (GENERAL_COVENANT_DEDICATED_OWNERS[code]) {
    return Object.freeze({
      code,
      owner_id: GENERAL_COVENANT_DEDICATED_OWNERS[code],
      route_state: 'DEDICATED_FAMILY',
    });
  }
  if (GENERAL_COVENANT_FOLLOW_ON_OWNERS[code]) {
    return Object.freeze({
      code,
      owner_id: GENERAL_COVENANT_FOLLOW_ON_OWNERS[code],
      route_state: 'NARROW_FOLLOW_ON',
    });
  }
  return Object.freeze({
    code,
    owner_id: 'UNTYPED_GENERAL_COVENANT_REVIEW',
    route_state: 'REVIEW_REQUIRED',
  });
}

function isDedicatedFamilyCovenantCode(code) {
  return routeGeneralCovenantCode(code).route_state === 'DEDICATED_FAMILY';
}

