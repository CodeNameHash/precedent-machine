function suggestionPayload([key, decision, mergeInto, reason, deferToPhase]) {
  return {
    key,
    decision,
    merge_into: mergeInto || null,
    rename_to: key,
    defer_to_phase: deferToPhase || null,
    reason,
  };
}

function buildRegistryReviewSuggestions(fields, decisions = {}) {
  const keys = new Set((fields || []).map((field) => field.key));
  const suggestions = {};
  for (const row of EXPLICIT_SUGGESTIONS) {
    const suggestion = suggestionPayload(row);
    if (!keys.has(suggestion.key)) continue;
    if (decisions[suggestion.key]?.decision) continue;
    suggestions[suggestion.key] = suggestion;
  }
  return suggestions;
}

